"""Builds ../../10. test-execution/Selenium_Results.md from a pytest JUnit XML file.

Usage (from 8. automation-testing/selenium-or-playwright):
    pytest --junitxml=junit.xml --html=report.html --self-contained-html
    python tools/make_results_table.py junit.xml

Each test's docstring names its test case ID ("TC-M5-001 (R5.1): ..."), which is joined to
../../4. test-cases/Test_Cases.csv for the expected result.
"""
import csv
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
CSV = HERE.parents[1] / "4. test-cases" / "Test_Cases.csv"
OUT = HERE.parents[1] / "10. test-execution" / "Selenium_Results.md"


def doc_ids():
    """test function name -> TC id, read from the docstrings."""
    ids = {}
    for f in sorted((HERE / "tests").glob("test_*.py")):
        text = f.read_text(encoding="utf-8")
        for m in re.finditer(r"def (test_\w+)\(.*?\):\s*\n\s*\"\"\"(TC-M\d-\d{3})", text):
            ids[m.group(1)] = m.group(2)
    return ids


def main(junit):
    cases = {r["TC_ID"]: r for r in csv.DictReader(open(CSV, encoding="utf-8", newline=""))}
    ids = doc_ids()
    root = ET.parse(junit).getroot()
    rows, counts = [], {"passed": 0, "failed": 0, "error": 0, "skipped": 0}
    for tc in root.iter("testcase"):
        name = tc.get("name")
        tcid = ids.get(name, "?")
        status, actual = "passed", "Test assertions held."
        for tag in ("failure", "error", "skipped"):
            el = tc.find(tag)
            if el is not None:
                status = "failed" if tag == "failure" else tag
                actual = (el.get("message") or "").split("\n")[0][:160].replace("|", "/")
        counts[status] += 1
        c = cases.get(tcid, {})
        rows.append((tcid, c.get("Expected_Result", "")[:110].replace("|", "/"), actual, status,
                     f"`{tc.get('classname','').split('.')[-1]}::{name}`", f"{float(tc.get('time', 0)):.1f}s"))
    rows.sort(key=lambda r: r[0])
    total = sum(counts.values())
    lines = ["# Selenium results per test case", "",
             f"Source: `pytest --junitxml` run (see `10. test-execution/selenium_report.html`). "
             f"Generated by `8. automation-testing/selenium-or-playwright/14. tools/make_results_table.py`.", "",
             f"Total {total}: {counts['passed']} passed, {counts['failed']} failed, {counts['error']} errors, {counts['skipped']} skipped.", "",
             "| TC ID | Expected | Actual | Status | Evidence | Time |", "|---|---|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {d} | {e} | {f} |" for a, b, c, d, e, f in rows]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(counts, "->", OUT)


if __name__ == "__main__":
    main(sys.argv[1])
