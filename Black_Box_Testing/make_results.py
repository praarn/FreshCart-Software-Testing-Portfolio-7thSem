"""Builds Black_Box_Results.md from results/black_box_junit.xml and Test_Cases.csv.

Usage (from this folder, after a run):  python make_results.py
Every number in the output comes from the JUnit file; nothing is typed by hand.
"""
import csv
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES = HERE.parent / "Test_Case_Design" / "Test_Cases.csv"

suite = ET.parse(HERE / "results" / "black_box_junit.xml").getroot()
suite = suite if suite.tag == "testsuite" else suite.find("testsuite")
meta = {r["TC_ID"]: r for r in csv.DictReader(open(CASES, encoding="utf-8", newline="")) if r["Automated"] == "B"}

per_tc = defaultdict(lambda: {"tests": 0, "failed": 0, "skipped": 0})
for case in suite.iter("testcase"):
    tcs = next((p.get("value") for p in case.iter("property") if p.get("name") == "tc"), "")
    outcome = "failed" if case.find("failure") is not None or case.find("error") is not None else (
        "skipped" if case.find("skipped") is not None else "ok")
    for tc in filter(None, tcs.split(",")):
        row = per_tc[tc]
        row["tests"] += 1
        if outcome != "ok":
            row[outcome] += 1

total = int(suite.get("tests"))
failed = int(suite.get("failures")) + int(suite.get("errors"))
skipped = int(suite.get("skipped"))
unknown = sorted(set(per_tc) - set(meta))
missing = sorted(set(meta) - set(per_tc))

out = ["# Black-box results: equivalence partitioning and boundary value analysis", "",
       f"Run: `{suite.get('timestamp', '')[:19].replace('T', ' ')}`, {float(suite.get('time')):.0f} s, against the backend in test mode "
       "(`APP_ENV=test FIXED_NOW=2026-11-10T09:00:00`). Generated by `make_results.py` from "
       "[`results/black_box_junit.xml`](results/black_box_junit.xml); the console log is "
       "[`results/black_box_run.log`](results/black_box_run.log).", "",
       "| | |", "|---|---|",
       f"| parametrized tests (each is one class or one boundary value) | {total} |",
       f"| Passed | {total - failed - skipped} |", f"| Failed | {failed} |", f"| Skipped | {skipped} |",
       f"| Test cases covered | {len(set(per_tc) & set(meta))} of {len(meta)} |", ""]

for kind, label in (("Black-box EP", "Method 1: equivalence partitioning"), ("Black-box BVA", "Method 2: boundary value analysis")):
    rows = [(tc, m) for tc, m in sorted(meta.items()) if m["Type"] == kind]
    n_tests = sum(per_tc[tc]["tests"] for tc, _ in rows)
    n_fail = sum(per_tc[tc]["failed"] for tc, _ in rows)
    out += [f"## {label}", "", f"{len(rows)} cases, {n_tests} parametrized tests, {n_fail} failed.", "",
            "| Test case | Rules | What is probed | Tests | Failed |", "|---|---|---|---|---|"]
    for tc, m in rows:
        out.append(f"| `{tc}` | {m['Rule_IDs']} | {m['Title'].split(': ', 1)[-1]} | {per_tc[tc]['tests']} | {per_tc[tc]['failed']} |")
    out.append("")

if unknown or missing:
    out += ["## Mismatches", "", f"Tests naming a case that is not a `B` row in the CSV: {unknown or 'none'}. "
            f"`B` rows with no test in the run: {missing or 'none'}.", ""]
(HERE / "Black_Box_Results.md").write_text("\n".join(out), encoding="utf-8")
print(f"{total} tests, {failed} failed, {skipped} skipped; {len(set(per_tc) & set(meta))}/{len(meta)} cases")
