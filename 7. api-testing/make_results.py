"""Builds API_Test_Results.md from a Newman JSON report.

Usage:  python make_results.py reports/newman_report.json
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main(path):
    data = json.load(open(path, encoding="utf-8"))
    run = data["run"]
    # pm.sendRequest helper calls made by a pre-request script share the parent item's id and are
    # recorded before it; the item's own request is the last execution with that id.
    by_id = {}
    for e in run["executions"]:
        by_id[e["item"]["id"]] = e
    execs = list(by_id.values())
    helpers = len(run["executions"]) - len(execs)
    rows, folder_stats = [], {}
    for n, e in enumerate(execs, 1):
        name = e["item"]["name"]
        m = re.match(r"\[([^\]]+)\] (.*)", name)
        tc, title = (m.group(1), m.group(2)) if m else ("", name)
        req = e["request"]
        method = req["method"]
        p = "/" + "/".join(req["url"].get("path", []))
        resp = e.get("response") or {}
        code = resp.get("code", "-")
        asserts = e.get("assertions", [])
        exp = next((re.sub(r"status is (one of )?", "", a["assertion"]) for a in asserts if a["assertion"].startswith("status is")), "-")
        failed = [a for a in asserts if a.get("error")]
        ok = not failed and resp
        desc = e["item"].get("description") or {}
        desc = desc.get("content", "") if isinstance(desc, dict) else str(desc)
        rule = re.sub(r"^Rule\(s\): ", "", desc)
        rows.append((n, tc, title.replace("|", "/"), f"{method} {p}", exp, code, "PASS" if ok else "FAIL", rule))
    stats = run["stats"]
    total_assert = stats["assertions"]["total"]
    failed_assert = stats["assertions"]["failed"]
    folders = {}
    for item in json.load(open(HERE / "FreshCart.postman_collection.json", encoding="utf-8"))["item"]:
        folders[item["name"]] = len(item["item"])
    neg = sum(1 for r in rows if str(r[4]).startswith(("4", "[4")))
    out = ["# API test results (Newman)", "",
           "Collection: [`FreshCart.postman_collection.json`](FreshCart.postman_collection.json), generated by "
           "`build_collection.py`. Raw reports: [`reports/newman_report.json`](reports/newman_report.json), "
           "[`reports/newman_report.html`](reports/newman_report.html).", "",
           "| Metric | Value |", "|---|---|",
           f"| Requests defined and executed | {len(rows)} |",
           f"| Helper calls made by pre-request scripts (setup data, rate-limit probes) | {helpers} |",
           f"| Assertions | {total_assert} ({failed_assert} failed) |",
           f"| Requests expecting a 4xx status (negative checks) | {neg} |",
           f"| Requests passed / failed | {sum(1 for r in rows if r[6]=='PASS')} / {sum(1 for r in rows if r[6]=='FAIL')} |", "",
           "## Requests per folder", "", "| Folder | Requests |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in folders.items()]
    out += ["", "## Results", "",
            "Expected status is the first assertion of each request; every request also asserts response shape or the "
            "`{status, error, message, field_errors}` contract. TC IDs refer to `4. test-cases/Test_Cases.csv`; "
            "`API-*` and `DEF-*` are API-only checks.", "",
            "| # | TC | Request | Call | Expected | Actual | Result | Rules |", "|---|---|---|---|---|---|---|---|"]
    out += [f"| {a} | {b} | {c} | `{d}` | {e} | {f} | {g} | {h} |" for a, b, c, d, e, f, g, h in rows]
    (HERE / "API_Test_Results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(len(rows), "rows;", total_assert, "assertions,", failed_assert, "failed")


if __name__ == "__main__":
    main(sys.argv[1])
