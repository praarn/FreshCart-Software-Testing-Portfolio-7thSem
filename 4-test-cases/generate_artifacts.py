"""Regenerates Traceability_Matrix.md and Functional_Test_Cases.xlsx from Test_Cases.csv.

Usage (from this folder):  python generate_artifacts.py      (needs: pip install openpyxl)
Prints the summary counts that the READMEs quote.
"""
import collections
import csv
import re
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

HERE = Path(__file__).resolve().parent
REQ = HERE.parent / "0-application" / "docs" / "REQUIREMENTS.md"
MODULES = {
    "M1": "Registration and login", "M2": "Catalog", "M3": "Cart", "M4": "Coupons and pricing",
    "M5": "Checkout", "M6": "Orders and lifecycle", "M7": "Reviews", "M8": "Admin",
    "M9": "Wishlist, banners and offers",
}
AUTOMATED = {"Y": "Selenium", "A": "API (Newman)", "B": "Black-box EP/BVA suite (pytest)", "U": "Unit (pytest)", "N": "Manual"}


def rule_ids():
    return re.findall(r"^\| (R\d\.\d) \|", REQ.read_text(encoding="utf-8"), flags=re.M)


def main():
    rows = list(csv.DictReader(open(HERE / "Test_Cases.csv", encoding="utf-8", newline="")))
    by_rule = collections.defaultdict(list)
    for r in rows:
        for rid in [x.strip() for x in r["Rule_IDs"].split(",")]:
            by_rule[rid].append(r["TC_ID"])
    rules = rule_ids()
    uncovered = [x for x in rules if not by_rule.get(x)]

    out = ["# Requirements Traceability Matrix", "",
           "Maps every business rule in [`../0-application/docs/REQUIREMENTS.md`](../0-application/docs/REQUIREMENTS.md)",
           "to the test case(s) in [`Test_Cases.csv`](Test_Cases.csv). Generated by `generate_artifacts.py`;",
           "regenerate rather than hand-edit.", ""]
    for m, title in MODULES.items():
        out += [f"## {m} - {title}", "", "| Rule ID | Test Case(s) |", "|---|---|"]
        for rid in rules:
            if rid.startswith("R" + m[1]):
                out.append(f"| {rid} | " + ", ".join(f"`{t}`" for t in dict.fromkeys(by_rule[rid])) + " |")
        out.append("")
    auto = collections.Counter(r["Automated"] for r in rows)
    out += ["## Summary", "",
            f"- {len(rules)} rules, {len(rules) - len(uncovered)} covered by at least one test case",
            f"- {len(rows)} test cases total",
            "- " + ", ".join(f"{v} {AUTOMATED[k]} (`{k}`)" for k, v in sorted(auto.items(), key=lambda kv: "YABUN".index(kv[0]))), ""]
    (HERE / "Traceability_Matrix.md").write_text("\n".join(out), encoding="utf-8")

    wb = Workbook()
    ws = wb.active
    ws.title = "Test Cases"
    hdr = list(rows[0].keys())
    ws.append(hdr)
    for r in rows:
        ws.append([r[h] for h in hdr])
    fill = PatternFill("solid", fgColor="1F4E78")
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = fill
        c.alignment = Alignment(vertical="center", wrap_text=True)
    widths = {"TC_ID": 11, "Module": 8, "Rule_IDs": 12, "Title": 48, "Type": 18, "Priority": 9,
              "Preconditions": 34, "Steps": 50, "Test_Data": 28, "Expected_Result": 46, "Automated": 10}
    for i, h in enumerate(hdr, 1):
        ws.column_dimensions[get_column_letter(i)].width = widths.get(h, 20)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(vertical="top", wrap_text=True)
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = ws.dimensions

    s = wb.create_sheet("Summary")
    s.append(["Cut", "Value", "Count"])
    s.append(["Total cases", "", len(rows)])
    for k, v in sorted(auto.items()):
        s.append(["Automation", AUTOMATED[k], v])
    for k, v in collections.Counter(r["Priority"] for r in rows).items():
        s.append(["Priority", k, v])
    for k, v in collections.Counter(r["Type"] for r in rows).items():
        s.append(["Type", k, v])
    for k, v in collections.Counter(r["Module"] for r in rows).items():
        s.append(["Module", k, v])
    for c in s[1]:
        c.font = Font(bold=True)
    s.column_dimensions["A"].width = 14
    s.column_dimensions["B"].width = 26
    wb.save(HERE / "Functional_Test_Cases.xlsx")

    print("total", len(rows), "rules", len(rules), "uncovered", uncovered)
    print("automation", dict(auto))
    print("priority", dict(collections.Counter(r["Priority"] for r in rows)))
    print("type", dict(collections.Counter(r["Type"] for r in rows)))


if __name__ == "__main__":
    main()
